    def test_axis_ghost_cells_use_absolute_radius_measure(self):
        nghost = 4
        nx = 12
        extent = nx + 2 * nghost
        dr = 0.25
        face_r = (np.arange(extent) - nghost) * dr
        values = np.tile(face_r ** 3, (2, 1))
        result = mhd_num.radial_face_samples_to_cell_average(
            values, nghost, origin_x=0.0, dr=dr)
        for q in range(3, extent - 4):
            r_lo = (q - nghost) * dr
            expected = _ring_average_power(r_lo, r_lo + dr, 3)
            self.assertAlmostEqual(result[0, q], expected, places=12)

    def test_rejects_a_cell_that_straddles_the_axis(self):
        with self.assertRaisesRegex(ValueError, "straddle"):
            mhd_num.radial_face_samples_to_cell_average(
                np.ones((2, 10)), nghost=2, origin_x=0.25, dr=1.0)

    def test_rejects_invalid_scheme_order(self):
        values = np.ones((2, 12))
        for invalid in (True, 1, 6, 5.5, "mp5", np.nan):
            with self.subTest(scheme_order=invalid):
                with self.assertRaisesRegex(ValueError, "scheme_order"):
                    mhd_num.radial_face_samples_to_cell_average(
                        values, nghost=2, origin_x=1.0, dr=0.1,
                        scheme_order=invalid)

    def test_rejects_extent_smaller_than_explicit_scheme_stencil(self):
        with self.assertRaisesRegex(ValueError, "smaller"):
            mhd_num.radial_face_samples_to_cell_average(
                np.ones((2, 6)), nghost=1, origin_x=1.0, dr=0.1,
                scheme_order=7)


