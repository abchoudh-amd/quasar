    def test_one_sided_closure_folds_radius_into_gauss_weights(self):
        nghost = 4
        nx = 12
        extent = nx + 2 * nghost
        dr = 0.125
        origin_x = 1.0
        face_r = origin_x + (np.arange(extent) - nghost) * dr
        # Four-point Gauss integration remains exact through degree six in the
        # sampled polynomial after multiplication by the linear radial metric.
        for degree in range(7):
            values = np.tile(face_r ** degree, (2, 1))
            result = mhd_num.radial_face_samples_to_cell_average(
                values, nghost, origin_x, dr)
            for q in (0, 1, 2, extent - 4, extent - 3, extent - 2, extent - 1):
                r_lo = origin_x + (q - nghost) * dr
                expected = _ring_average_power(r_lo, r_lo + dr, degree)
                self.assertAlmostEqual(
                    result[0, q], expected, places=11,
                    msg=f"degree={degree}, q={q}")

