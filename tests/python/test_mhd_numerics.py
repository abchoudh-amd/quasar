    def test_centered_rows_recover_ring_average_polynomials(self):
        nghost = 4
        nx = 12
        extent = nx + 2 * nghost
        dr = 0.125
        origin_x = 1.0
        face_r = origin_x + (np.arange(extent) - nghost) * dr
        for degree in range(8):
            values = np.tile(face_r ** degree, (3, 1))
            result = mhd_num.radial_face_samples_to_cell_average(
                values, nghost, origin_x, dr)
            # Width-eight centered stencils exist for q=3..extent-5.
            for q in range(3, extent - 4):
                r_lo = origin_x + (q - nghost) * dr
                expected = _ring_average_power(r_lo, r_lo + dr, degree)
                self.assertAlmostEqual(
                    result[1, q], expected, places=11,
                    msg=f"degree={degree}, q={q}")

    def test_mp5_width_is_independent_of_an_overpadded_halo(self):
        nghost = 4
        nx = 12
        extent = nx + 2 * nghost
        dr = 0.125
        origin_x = 1.0
        face_r = origin_x + (np.arange(extent) - nghost) * dr
