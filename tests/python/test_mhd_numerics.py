from quasar.mhd import numerics as mhd_num


def _ring_average_power(r_lo, r_hi, degree):
    """Exact average of ``r**degree`` under ``abs(r) dr`` on one cell."""
    def primitive(radius, power):
        value = radius ** (power + 2) / (power + 2)
        return value if radius >= 0.0 else -value

    volume = primitive(r_hi, 0) - primitive(r_lo, 0)
    moment = primitive(r_hi, degree) - primitive(r_lo, degree)
    return moment / volume


